@app.post("/api/exam/start")
def exam_start(request: ExamStartRequest):
    questions = _exam_questions(request.part)
    cases = [c for c in _cases if c.get("questions") and c.get("part") == request.part]
    if len(cases) > 2:
        cases = random.sample(cases, 2)
    return {
        "part": request.part,
        "mcq_count": len(questions),
        "mcq_time_minutes": 180,
        "case_time_minutes": 60,
        "format_note": "Timed MCQ practice with short case exercises, not a complete replica of the CMA case section.",
        "mcq_questions": [_public_exam_question(q) for q in questions],
        "cases": [_public_case(c) for c in cases],
        "blueprint": _BLUEPRINT[request.part],
    }


@app.post("/api/exam/grade")
def exam_grade(request: ExamGradeRequest):
    q = get_question(request.question_id)
    if not q:
        raise HTTPException(status_code=404, detail="Question not found")
    ok, _graded = grade(request.question_id, request.selected, request.confidence, request.session_id)
    # Exam answers are recorded in history but deliberately do not enter the
    # spaced-review scheduler because the simulation has no confidence input.
    return {"correct": bool(ok)}


@app.get("/api/summary")
def summary():
    """Lightweight real-data summary for the practice UI hero."""
    c = db()
    row = c.execute("SELECT COUNT(*) AS attempted, COALESCE(SUM(correct),0) AS correct FROM attempts").fetchone()
    focus = c.execute("""
        SELECT domain, COUNT(*) AS n, COALESCE(SUM(correct),0) AS correct
        FROM attempts
        GROUP BY domain
        ORDER BY n DESC, domain ASC
        LIMIT 1
    """).fetchone()
    c.close()
    attempted = int(row["attempted"] or 0)
    correct = int(row["correct"] or 0)
    accuracy = round(correct / attempted * 100, 1) if attempted else 0
    regular_bank = [q for q in engine.QUESTIONS if not q.get("is_case")]
    return {
        "attempted": attempted,
        "accuracy": accuracy,
        "focus_domain": focus["domain"] if focus else "Build coverage",
        "question_bank_size": len(regular_bank),
    }


