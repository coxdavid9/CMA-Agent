_original_db = engine.db
_schema_ready = False


def db():
    global _schema_ready
    if not engine.DATABASE_URL:
        return _original_db()
    c = engine._PostgresConnection()
    if not _schema_ready:
        c.execute("CREATE TABLE IF NOT EXISTS attempts(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ts TEXT,question_id TEXT,part TEXT,domain TEXT,difficulty TEXT,selected TEXT,correct INTEGER,confidence INTEGER,session_id TEXT)")
        c.execute("CREATE TABLE IF NOT EXISTS goals(id INTEGER PRIMARY KEY CHECK(id=1),target_date TEXT,part TEXT,daily_minutes INTEGER)")
        c.execute("CREATE TABLE IF NOT EXISTS study_plans(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,created_at TEXT,target_date TEXT,part TEXT,daily_minutes INTEGER)")
        c.execute("CREATE TABLE IF NOT EXISTS preferences(id INTEGER PRIMARY KEY CHECK(id=1),part TEXT,difficulty TEXT,domain TEXT,resume_question_id TEXT)")
        c.execute("CREATE TABLE IF NOT EXISTS session_state(id INTEGER PRIMARY KEY CHECK(id=1),session_id TEXT,last_activity TEXT)")
        c.execute("CREATE INDEX IF NOT EXISTS idx_attempts_question ON attempts(question_id)")
        c.execute("CREATE INDEX IF NOT EXISTS idx_attempts_domain ON attempts(domain)")
        c.execute("CREATE INDEX IF NOT EXISTS idx_attempts_session ON attempts(session_id)")
        c.execute("CREATE INDEX IF NOT EXISTS idx_attempts_ts ON attempts(ts)")
        c.commit()
        _schema_ready = True
    return c


