_CONTEXT_TAILS = (
    " for a manufacturing business.",
    " when evaluating a current-period decision.",
    " when comparing two operating alternatives.",
    " in a multi-site organization.",
    " for a manager preparing a forecast.",
    " when analyzing the current reporting period.",
    " when reviewing the underlying business drivers.",
    " for a monthly management review.",
)


def clean_question(q):
    if not q:
        return q
    result = copy.deepcopy(q)
    result.pop("numeric_check", None)
    result.pop("content_revision", None)
    text = result.get("question")
    if isinstance(text, str):
        for tail in _CONTEXT_TAILS:
            if text.endswith(tail):
                result["question"] = text[:-len(tail)].rstrip()
                break
    return result


def _public_exam_question(q):
    result = clean_question(q)
    for key in ("answer", "explanation", "calculation"):
        result.pop(key, None)
    return result


def _recent_question_ids(limit=15):
    c = db()
    rows = c.execute("SELECT question_id FROM attempts ORDER BY id DESC LIMIT ?", (limit,)).fetchall()
    ids = [r["question_id"] for r in rows]
    c.close()
    return ids


def _choose_case(part="Both", domain="All", exclude_case_ids=None):
    excluded = set(exclude_case_ids or [])
    eligible = [c for c in _cases if c.get("id") not in excluded
                and c.get("questions") and (part == "Both" or c.get("part") == part)
                and (domain == "All" or c.get("domain") == domain)]
    if not eligible:
        eligible = [c for c in _cases if c.get("questions") and (part == "Both" or c.get("part") == part)
                    and (domain == "All" or c.get("domain") == domain)]
    return random.choice(eligible) if eligible else None


def _public_case(case):
    result = copy.deepcopy(case)
    result.pop("written_practice", None)
    public_questions = []
    for idx, item in enumerate(case.get("questions", []), 1):
        public_questions.append({
            "id": f"{case['id']}-Q{idx}",
            "question": item.get("q", ""),
            "choices": item.get("choices", {}),
            "question_number": idx,
            "question_count": len(case.get("questions", [])),
        })
    result["questions"] = public_questions
    return result


