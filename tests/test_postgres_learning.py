"""Integration check against a disposable CI database, never production."""
import importlib
import json
import os
from pathlib import Path

import pytest


@pytest.mark.skipif(not os.getenv('CMA_TEST_POSTGRES_URL'), reason='Disposable Postgres URL not provided')
def test_postgres_legacy_schema_learning_and_assisted_history(monkeypatch):
    import psycopg
    from psycopg.rows import dict_row
    from cma_agent import engine, lessons, skills, adaptive
    url=os.environ['CMA_TEST_POSTGRES_URL']
    assert '/cma_learning_test' in url
    with psycopg.connect(url) as c:
        c.execute('CREATE TABLE attempts(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ts TEXT,question_id TEXT,part TEXT,domain TEXT,difficulty TEXT,selected TEXT,correct INTEGER,confidence INTEGER)')
        c.execute('CREATE TABLE preferences(id INTEGER PRIMARY KEY,part TEXT,difficulty TEXT,domain TEXT)')
        c.execute("INSERT INTO attempts(ts,question_id,correct,confidence) VALUES('2026-10-01','legacy',1,3)")
        c.execute("INSERT INTO preferences VALUES(1,'Both','All','All')")
    monkeypatch.setattr(engine,'DATABASE_URL',url)
    monkeypatch.setattr(engine,'_postgres_connection',lambda:psycopg.connect(url,row_factory=dict_row))
    (Path(__file__).parents[1]/'frontend/dist').mkdir(exist_ok=True)
    api=importlib.import_module('api')
    monkeypatch.setattr(api,'_schema_ready',False)
    run=lessons.start('npv')
    assert lessons.start('npv')['run_id']==run['run_id']
    for step in range(5):
        run=lessons.act(run['run_id'],0,'teach_next',str(step))
    while not run['done']:
        c=engine.db()
        state=json.loads(c.execute('SELECT state FROM lesson_runs WHERE id=?',(run['run_id'],)).fetchone()['state'])
        c.close()
        task=state['tasks'][run['index']]
        run=lessons.act(run['run_id'],run['index'],'answer',str(task['answer']))
        run=lessons.act(run['run_id'],run['index'],'next')
    assert run['outcome']=='Independent check passed'
    q=engine.QUESTIONS[0]
    engine.grade(q['id'],q['answer'],3,'postgres-test',hint_level=2)
    skills.record_attempt(q,True,3,2)
    adaptive.record_result(q['id'],True,3,2)
    assert skills.snapshot()['priorities'][0]['independent_attempts']==0
    c=engine.db()
    assert c.execute("SELECT correct FROM attempts WHERE question_id='legacy'").fetchone()['correct']==1
    assert c.execute('SELECT resume_question_id FROM preferences WHERE id=1').fetchone()['resume_question_id'] is None
    assert c.execute('SELECT hint_level FROM attempts WHERE question_id=?',(q['id'],)).fetchone()['hint_level']==2
    c.close()
